def load(name, file):
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / file)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


policy = load("policy", "check-policy.py")
result = load("aggregate", "check-result.py")
TEXT = (ROOT / "fixtures/declaration/MAINTENANCE.md").read_text()
RULES = declaration.source_policy(TEXT)
PRIVATE = "/".join(("", "Users", "fixture-owner", "project"))
TASK = ".agent" + "/plans/task.md"
TOOL_TRAILER = "Co-Authored" + "-By: Claude <noreply@anthropic.com>"
GENERATED = "Generated" + " with AI assistant"


class PolicyRulesTests(unittest.TestCase):
    def test_rules_come_from_the_supplied_declaration(self):
        changed = TEXT.replace("name `showxu`", "name `another`").replace("`feat`,", "`feature`,")
        parsed = declaration.source_policy(changed)
        self.assertEqual(parsed["owner"], "another")
        self.assertIn("feature", parsed["types"])
        self.assertNotIn("feat", parsed["types"])
        for phrase in ("are SSH-signed", "Dependabot may author changes.", "real human co-authors may be credited.",
                       "added or modified paths", "gpg.format ssh"):
            with self.subTest(phrase=phrase), self.assertRaises(ValueError):
                declaration.source_policy(re.sub(r"\s+".join(map(re.escape, phrase.split())), "changed rule", TEXT))

    def test_all_declared_conventional_types_and_optional_scope_bang(self):
        for kind in RULES["types"]:
            for suffix in (": update", "(runtime): update", "!: update", "(runtime)!: update"):
                self.assertEqual(policy.message_findings("commit", kind + suffix, RULES), [])
        for subject in ("update runtime", "feature: update", "fix:", "fix: ", "fix(): update", "fix: update "):
            self.assertTrue(policy.message_findings("commit", subject, RULES))

    def test_human_attribution_and_technical_terms_are_allowed(self):
        for text in ("feat: support Claude and Codex", "fix: update\n\nCo-Authored-By: Jane Doe <jane@example.org>",
                     "fix: update\n\nCo-Authored-By: Claude Martin <claude@example.org>",
                     "feat: Generated by Jane Doe", "fix: update\n\nPowered-by: SQLite",
                     "docs: Generated with a compiler",
                     "docs: Generated by Codexia", "docs: Generated by Jane <noreply@example.org>"):
            self.assertEqual(policy.message_findings("commit", text, RULES), [])

    def test_tool_attribution_in_messages_and_added_lines_is_rejected(self):
        for line in (TOOL_TRAILER, GENERATED, "Generated" + "-by: AI assistant", "# " + GENERATED,
                     "Co-Authored" + "-By: helper[bot]"):
            self.assertTrue(policy.message_findings("commit", "fix: update\n\n" + line, RULES))
            self.assertTrue(policy.added_findings("@@ -0,0 +1 @@\n+" + line + "\n", "file"))

    def test_attribution_checks_tool_identity_in_every_message_position(self):
        for identity in ("Codex", "Claude Code", "[ChatGPT](https://example.org)",
                         "helper[bot]", "Helper <noreply@openai.com>"):
            for statement in ("Generated by " + identity, "Generated with " + identity,
                              "Co-Authored-By: " + identity, "Signed-off-by: " + identity):
                for text in ("feat: " + statement, "feat: update\n\n" + statement):
                    with self.subTest(text=text):
                        self.assertTrue(policy.message_findings("message", text, RULES))
        self.assertTrue(policy.attribution("Generated" + " by Codex for this project"))
        self.assertTrue(policy.attribution("Signed-off" + "-by: dependabot[bot] <support@github.com>"))

    def test_quoted_and_multiple_attribution_statements_are_checked(self):
        statement = "Generated" + " by Codex"
        for quote in ('"', "'"):
            self.assertTrue(policy.attribution("feat: " + quote + statement + quote))
        for prefix in ("Powered-by: SQLite; ", "Generated by Jane Doe; "):
            self.assertTrue(policy.attribution("feat: " + prefix + statement))
        self.assertFalse(policy.attribution("feat: Generated by Jane Doe; Powered-by: SQLite"))

    def test_tool_inventory_names_and_emails_are_recognized(self):
        inventory = json.loads((ROOT / "data/attribution-tools.json").read_text())
        for name in inventory["names"]:
            with self.subTest(name=name):
                self.assertTrue(policy.attribution("Generated with " + name.upper()))
                self.assertFalse(policy.attribution("Co-Authored-By: " + name + " <tool@example.org>"))
                self.assertTrue(policy.attribution("Co-Authored-By: " + name))
        for email in inventory["emails"]:
            with self.subTest(email=email):
                self.assertTrue(policy.attribution("Co-Authored-By: Helper <" + email.upper() + ">"))
        self.assertFalse(policy.attribution("Co-Authored-By: Jane <noreply@openai.com.example.org>"))

    def test_path_exception_input_is_relative_and_line_delimited(self):
        self.assertEqual(policy.parse_path_exceptions(""), ())
        self.assertEqual(policy.parse_path_exceptions(" fixtures/* \n\n vendor/**/*.md\n"),
                         ("fixtures/*", "vendor/**/*.md"))
        for pattern in ("/absolute/*", "../outside/*", "fixtures/../*", "C:/Users/*", "./fixtures/*",
                        "fixtures\\*", "fixtures//file", "fixtures/"):
            with self.subTest(pattern=pattern), self.assertRaises(ValueError):
                policy.parse_path_exceptions(pattern)

    def test_private_paths_and_task_references(self):
        for text in (PRIVATE, PRIVATE.replace("fixture-owner", "Jane Doe"), PRIVATE.replace("fixture-owner", "用户"),
                     PRIVATE.rsplit("/", 1)[0], TASK, "file://" + PRIVATE, "[local](" + TASK + ")"):
            self.assertTrue(policy.content_findings("file", text))
        self.assertTrue(policy.content_findings("path", TASK, path=True))
        # Policy descriptions and product names are not local execution paths.
        for text in ("/Users/<name>/", "local task state", "docs/Claude.md", "PLAN.md", "file.plan.md"):
            self.assertEqual(policy.content_findings("file", text, path=True), [])

    def test_added_lines_exclude_context_and_deletions_and_include_plus_prefix(self):
        patch_text = "@@ -1,2 +1,2 @@\n-" + PRIVATE + "\n context\n+++ " + PRIVATE + "\n"
        findings = policy.added_findings(patch_text, "file")
        self.assertEqual(len(findings), 1)
        self.assertIn(":2:", findings[0])
        self.assertEqual(policy.added_findings("@@ -1 +1 @@\n-" + PRIVATE + "\n+safe\n", "file"), [])

    def test_no_undeclared_whitespace_conflict_or_product_term_rules(self):
        self.assertEqual(policy.added_findings("@@ -0,0 +1,4 @@\n+Claude\n+trailing  \n+<<<<<<< marker\n+\n", "file"), [])

    def record(self, owner=True):
        return {"sha": "a" * 40, "author": {"login": "dependabot[bot]", "type": "Bot"},
                "committer": {"login": RULES["owner"] if owner else "web-flow"},
                "commit": {"committer": {"name": RULES["owner"] if owner else "GitHub",
                                         "email": RULES["email"] if owner else "noreply@github.com"},
                           "verification": {"verified": True, "reason": "valid",
                                            "signature": "-----BEGIN SSH SIGNATURE-----" if owner else "PGP"}}}

    def test_verified_owner_ssh_and_github_commits_accept_external_authors(self):
        for owner in (True, False):
            self.assertEqual(policy.commit_findings("a" * 40, self.record(owner), RULES), [])

    def test_unverified_wrong_identity_sha_and_owner_signature_fail(self):
        for field, value in (("verified", False), ("reason", "unknown_key"), ("signature", "PGP")):
            record = self.record()
            record["commit"]["verification"][field] = value
            self.assertTrue(policy.commit_findings("a" * 40, record, RULES))
        for field in ("name", "email"):
            record = self.record()
            record["commit"]["committer"][field] = "someone"
            self.assertTrue(policy.commit_findings("a" * 40, record, RULES))
        record = self.record()
        record["committer"]["login"] = "spoofed"
        self.assertTrue(policy.commit_findings("a" * 40, record, RULES))
        self.assertTrue(policy.commit_findings("b" * 40, self.record(), RULES))


class GitRangeTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.git("init", "-q", "-b", "master")
        self.git("config", "user.name", "Fixture")
        self.git("config", "user.email", "fixture@example.org")
        self.git("config", "commit.gpgsign", "false")
        self.write("sample.txt", "base\n")
        self.base = self.commit("feat: initial")
        self.api = Mock()

    def git(self, *args):
        return policy.git(self.root, *args).strip()

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    def commit(self, message):
        self.git("add", "--all")
        self.git("commit", "-q", "-m", message)
        return self.git("rev-parse", "HEAD")

    def event(self, head, title="feat: change"):
        return {"repository": {"full_name": "computer-mcp/widget", "default_branch": "master"},
                "pull_request": {"head": {"sha": head}, "base": {"sha": self.base}, "title": title}}

    def test_pr_checks_title_messages_content_and_paths_without_signature_api(self):
        self.write("sample.txt", "base\n" + PRIVATE + "\n")
        self.write(TASK, "private task\n")
        head = self.commit("invalid subject")
        findings = policy.check(self.root, self.event(head, "invalid title"), "pull_request", RULES, self.api)
        self.assertTrue(any("PR title" in f for f in findings))
        self.assertTrue(any(head in f for f in findings))
        self.assertTrue(any("machine path" in f for f in findings))
        self.assertTrue(any("local task state" in f for f in findings))
        self.api.get.assert_not_called()

    def test_file_exceptions_cover_fixtures_and_third_party_text_but_not_leaks(self):
        self.write("fixtures/path.txt", PRIVATE + "\n" + TASK + "\n")
        self.write("vendor/upstream/README.md", PRIVATE + "\n" + TASK + "\n")
        self.write("src/config.txt", PRIVATE + "\n" + TASK + "\n")
        head = self.commit("test: add path cases")
        default = policy.check(self.root, self.event(head), "pull_request", RULES, self.api)
        self.assertEqual(len(default), 6)
        patterns = policy.parse_path_exceptions("fixtures/*\nvendor/*")
        findings = policy.check(self.root, self.event(head), "pull_request", RULES, self.api,
                                path_exceptions=patterns)
        self.assertEqual(len(findings), 2)
        self.assertTrue(all(f.startswith("src/config.txt:") for f in findings))

    def test_exceptions_cover_task_paths_but_preserve_attribution_and_messages(self):
        self.write(TASK, PRIVATE + "\n" + TOOL_TRAILER + "\n")
        head = self.commit("feat: " + GENERATED + "\n\n" + PRIVATE)
        findings = policy.check(self.root, self.event(head, "feat: " + GENERATED), "pull_request", RULES,
                                self.api, path_exceptions=("*",))
        self.assertEqual(len(findings), 4)
        self.assertTrue(any(f.startswith("PR title:") for f in findings))
        self.assertTrue(any(f.startswith(head + ": private machine") for f in findings))
        self.assertTrue(any(f.startswith(TASK + ":2: tool") for f in findings))
        self.assertFalse(any("local task state" in f for f in findings))

    def test_cli_passes_path_exceptions_to_file_checks(self):
        self.write("fixtures/path.txt", PRIVATE + "\n")
        head = self.commit("test: add fixture")
        event = self.root / "event.json"
        event.write_text(json.dumps(self.event(head)))
        arguments = ["--root", str(self.root), "--declaration-root", str(ROOT / "fixtures/declaration"),
                     "--declaration-revision", "1" * 40, "--event", str(event),
                     "--event-name", "pull_request", "--fixture", str(ROOT / "fixtures/organization.json")]
        with redirect_stdout(io.StringIO()):
            self.assertEqual(policy.main(arguments), 1)
            self.assertEqual(policy.main(arguments + ["--path-exceptions", "fixtures/*"]), 0)

    def test_cli_attribution_uses_same_rules_in_pr_and_commit_fields(self):
        rejected = [
            "Generated" + " by Codex",
            "Generated by " + "Claude Martin",
            "Co-Authored-By: " + "Claude Martin",
            "Generated" + " by Claude Code v2.0",
            "Generated" + " by Codex CLI",
            "🤖 Generated with " + "[Claude Code](https://example.org)",
            "Co-Authored" + "-By: Helper <noreply@openai.com>",
            "Generated" + " by noreply@anthropic.com",
            "Made with " + "Codex (automation)",
            "Powered by " + "Codex https://example.org",
            "🤖 " + "Codex CLI",
        ]
        for phrase in ("Generated by", "Generated with", "Powered by", "Made with"):
            for name in ("Codex", "GitHub Copilot"):
                for phrase_space in (" ", "  ", "\t", " \t "):
                    for name_space in (" ", "  ", "\t", " \t "):
                        statement = phrase.replace(" ", phrase_space) + " " + name.replace(" ", name_space)
                        rejected.extend((statement, statement.swapcase()))
        allowed = [
            "Co-Authored-By: Claude <no_reply@openai.com>",
            "Co-Authored-By: Claude Martin <claude@example.org>",
            "Co-Authored-By: Codex <tool@example.org>",
            "Co-Authored-By: helper[bot] <helper@example.org>",
            "Co-Authored-By: Jane Doe <jane@example.com>",
            "Powered-by: SQLite", "Generated by Jane Doe",
            "Generated by Codexia", "Co-Authored-By: Jane <noreply@openai.com.example.org>",
        ]
        event_path = self.root / "event.json"
        arguments = ["--root", str(self.root), "--declaration-root", str(ROOT / "fixtures/declaration"),
                     "--declaration-revision", "1" * 40, "--event", str(event_path),
                     "--event-name", "pull_request", "--fixture", str(ROOT / "fixtures/organization.json")]
        for statement in rejected + allowed:
            for location in ("PR title", "PR body", "commit subject", "commit body", "commit trailer"):
                with self.subTest(statement=statement, location=location):
                    message = "fix: update"
                    if location == "commit subject":
                        message = "fix: " + statement
                    elif location == "commit body":
                        message += "\n\n" + statement + "\n\nDetails."
                    elif location == "commit trailer":
                        message += "\n\nDetails.\n\n" + statement
                    self.git("commit", "--allow-empty", "-q", "-m", message)
                    head = self.git("rev-parse", "HEAD")
                    event = self.event(head)
                    if location == "PR title":
                        event["pull_request"]["title"] = "fix: " + statement
                    elif location == "PR body":
                        event["pull_request"]["body"] = statement
                    event_path.write_text(json.dumps(event))
                    output = io.StringIO()
                    with redirect_stdout(output):
                        self.assertEqual(policy.main(arguments), int(statement in rejected))
                    if statement in rejected:
                        label = location if location.startswith("PR") else head
                        self.assertIn(label + ": tool or agent attribution", output.getvalue())
                    self.base = head

    def test_attributes_cannot_hide_added_text_or_execute_diff_helpers(self):
        self.write(".gitattributes", "sample.txt -diff\n")
        self.write("sample.txt", PRIVATE + "\n")
        head = self.commit("fix: update")
        self.assertTrue(policy.check(self.root, self.event(head), "pull_request", RULES, self.api))

    def test_deletions_and_unmodified_historical_content_are_preserved(self):
        self.write("sample.txt", PRIVATE + "\n")
        self.base = self.commit("feat: historical input")
        self.write("sample.txt", "safe\n")
        head = self.commit("fix: remove private input")
        self.assertEqual(policy.check(self.root, self.event(head), "pull_request", RULES, self.api), [])

    def test_renames_binary_paths_and_symlinks_are_checked(self):
        self.write("safe.txt", PRIVATE + "\n")
        self.base = self.commit("feat: historical input")
        self.git("mv", "safe.txt", "renamed.txt")
        (self.root / "link").symlink_to(PRIVATE)
        binary = self.root / TASK
        binary.parent.mkdir(parents=True)
        binary.write_bytes(b"\0\x01")
        findings = policy.check(self.root, self.event(self.commit("fix: move files")), "pull_request", RULES, self.api)
        self.assertTrue(any("renamed.txt" in f for f in findings))
        self.assertTrue(any("link" in f for f in findings))
        self.assertTrue(any(TASK in f for f in findings))

    def test_merge_base_excludes_unrelated_default_branch_changes(self):
        self.git("checkout", "-q", "-b", "feature")
        self.write("feature.txt", "feature\n")
        head = self.commit("feat: feature")
        self.git("checkout", "-q", "master")
        self.write("unrelated.txt", PRIVATE + "\n")
        self.base = self.commit("feat: unrelated")
        self.assertEqual(policy.check(self.root, self.event(head), "pull_request", RULES, self.api), [])

    def test_default_push_checks_all_new_commits_and_initial_push(self):
        self.write("sample.txt", "changed\n")
        first = self.commit("fix: first")
        self.write("sample.txt", "changed again\n")
        head = self.commit("fix: second")
        def record(path):
            value = PolicyRulesTests().record(False)
            value["sha"] = path.rsplit("/", 1)[1]
            return value
        self.api.get.side_effect = record
        event = {**self.event(head), "ref": "refs/heads/master", "before": self.base, "after": head}
        self.assertEqual(policy.check(self.root, event, "push", RULES, self.api), [])
        self.assertEqual([call.args[0].rsplit("/", 1)[1] for call in self.api.get.call_args_list], [first, head])
        event["before"] = policy.ZERO
        self.assertEqual(policy.check(self.root, event, "push", RULES, self.api), [])

    def test_queue_checks_queued_content_without_authenticating_synthetic_commit(self):
        self.write("sample.txt", PRIVATE)
        head = self.commit("Synthetic queued merge")
        event = {"merge_group": {"base_sha": self.base, "head_sha": head}}
        findings = policy.check(self.root, event, "merge_group", RULES, self.api)
        self.assertEqual(len(findings), 1)
        self.assertIn("machine path", findings[0])
        self.api.get.assert_not_called()


class ResultTests(unittest.TestCase):
    def test_all_success_and_optional_skip_pass(self):
        self.assertEqual(result.failures({"test": {"result": "success"}}, []), [])
        self.assertEqual(result.failures({"test": {"result": "success"}, "docs": {"result": "skipped"}}, ["docs"]), [])

    def test_failed_cancelled_required_skip_and_missing_results_fail(self):
        for state in ("failure", "cancelled", "skipped"):
            self.assertEqual(result.failures({"test": {"result": state}}, []), ["test"])
        for state in ("failure", "cancelled"):
            self.assertEqual(result.failures({"test": {"result": state}}, ["test"]), ["test"])
        for needs, optional in (({}, []), ({"test": {}}, []), ({"test": {"result": "success"}}, ["missing"]),
                                ({"test": {"result": "success"}}, "test")):
            with self.assertRaises(ValueError):
                result.failures(needs, optional)


